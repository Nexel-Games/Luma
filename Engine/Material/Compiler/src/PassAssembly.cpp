// Per-pass GLSL: each pass/stage source is a short generated header (pass,
// stage and material defines), the generated material functions
// LumaMaterialVertex / LumaMaterialPixel, then the hand-written pass template
// (material_*.vert/.frag in the engine shader directory) that supplies main().
// The shader compiler resolves the includes and hashes their contents into
// its cache key, so template edits recompile what they affect.

#include "PassAssembly.h"

#include <string_view>

namespace Luma::MaterialCompiler::Detail {
namespace {

using Material::BlendMode;
using Material::MaterialDomain;
using MaterialGraph::ValueType;

struct PinField {
    std::string_view pin;
    std::string_view field;
};

// Material Output pin -> MaterialPixel field (material_params.glsl).
constexpr PinField kPixelFields[] = {
    {"BaseColor", "baseColor"},
    {"Metallic", "metallic"},
    {"Specular", "specular"},
    {"Roughness", "roughness"},
    {"Anisotropy", "anisotropy"},
    {"EmissiveColor", "emissive"},
    {"Opacity", "opacity"},
    {"OpacityMask", "opacityMask"},
    {"Normal", "normal"},
    {"Tangent", "tangent"},
    {"SubsurfaceColor", "subsurfaceColor"},
    {"CustomData0", "customData0"},
    {"CustomData1", "customData1"},
    {"AmbientOcclusion", "ao"},
    {"Refraction", "refraction"},
    {"PixelDepthOffset", "pixelDepthOffset"},
};

std::string_view FieldOf(std::string_view pin) {
    for (const PinField& f : kPixelFields) {
        if (f.pin == pin) return f.field;
    }
    return {};
}

const char* PassDefine(Pass pass) {
    switch (pass) {
        case Pass::GBuffer: return "LUMA_PASS_GBUFFER";
        case Pass::DepthOnly: return "LUMA_PASS_DEPTH";
        case Pass::SelectionMask: return "LUMA_PASS_SELECTION";
        case Pass::Forward: return "LUMA_PASS_FORWARD";
        default: return "LUMA_PASS_POSTPROCESS";
    }
}

const char* FragmentTemplate(Pass pass) {
    switch (pass) {
        case Pass::GBuffer: return "material_gbuffer.frag";
        case Pass::DepthOnly: return "material_depth.frag";
        case Pass::SelectionMask: return "material_selection.frag";
        case Pass::Forward: return "material_forward.frag";
        default: return "material_postprocess.frag";
    }
}

const char* BlendDefine(BlendMode b) {
    switch (b) {
        case BlendMode::Masked: return "LUMA_BLEND_MASKED";
        case BlendMode::Translucent: return "LUMA_BLEND_TRANSLUCENT";
        case BlendMode::Additive: return "LUMA_BLEND_ADDITIVE";
        case BlendMode::Modulate: return "LUMA_BLEND_MODULATE";
        default: return "LUMA_BLEND_OPAQUE";
    }
}

bool Translucent(BlendMode b) {
    return b == BlendMode::Translucent || b == BlendMode::Additive || b == BlendMode::Modulate;
}

const MaterialOutputValue* Output(const CompiledMaterial& c, std::string_view pin) {
    for (const MaterialOutputValue& o : c.outputs) {
        if (o.pin == pin) return &o;
    }
    return nullptr;
}

std::string Header(const CompiledMaterial& c, const Material::MaterialSettings& s, Pass pass, Stage stage) {
    std::string h;
    h += "#version 450\n";
    h += "#extension GL_GOOGLE_include_directive : require\n";
    h += "#extension GL_EXT_nonuniform_qualifier : require\n";
    h += "// Generated by Luma::MaterialCompiler. Do not edit.\n";
    h += std::string("#define ") + PassDefine(pass) + " 1\n";
    h += stage == Stage::Vertex ? "#define LUMA_STAGE_VERTEX 1\n" : "#define LUMA_STAGE_PIXEL 1\n";
    h += "#define LUMA_SHADING_MODEL " + std::to_string(static_cast<int>(s.shadingModel)) + "\n";
    h += std::string("#define ") + BlendDefine(s.blendMode) + " 1\n";
    if (s.twoSided) h += "#define LUMA_TWO_SIDED 1\n";
    if (const MaterialOutputValue* pdo = Output(c, "PixelDepthOffset"); pdo && pdo->code != "0.0") {
        h += "#define LUMA_PIXEL_DEPTH_OFFSET 1\n";
    }
    if (Translucent(s.blendMode)) {
        if (s.refraction != Material::RefractionMethod::None) {
            h += "#define LUMA_REFRACTION " + std::to_string(static_cast<int>(s.refraction)) + "\n";
        }
        if (s.translucencyLighting == Material::TranslucencyLighting::Unlit) h += "#define LUMA_TRANSLUCENCY_UNLIT 1\n";
    }
    h += "#include \"material_params.glsl\"\n";
    h += "#include \"material_functions.glsl\"\n";
    for (const std::string& inc : c.includes) h += "#include \"" + inc + "\"\n";
    for (usize i = 0; i < c.interpolators.size(); ++i) {
        h += "layout(location = LUMA_INTERP_LOCATION + " + std::to_string(i) + ") " +
             (stage == Stage::Vertex ? "out " : "in ") + GlslType(c.interpolators[i].type) + " lumaInterp" +
             std::to_string(i) + ";\n";
    }
    if (!c.functions.empty()) h += "\n" + c.functions;
    return h;
}

std::string VertexSource(const CompiledMaterial& c, const Material::MaterialSettings& s, Pass pass) {
    std::string src = Header(c, s, pass, Stage::Vertex);
    src += "\nvoid LumaMaterialVertex(inout MaterialVertex V) {\n";
    src += c.vertexBody;
    for (const MaterialOutputValue& o : c.outputs) {
        if (o.stage != Stage::Vertex) continue;
        if (o.pin == "WorldPositionOffset") {
            src += "    V.worldPositionOffset = " + o.code + ";\n";
        } else if (o.pin.starts_with("CustomUV")) {
            const std::string index = o.pin.substr(8);
            src += "    V.customUV[" + index + "] = " + o.code + ";\n";
            src += "    V.customUVMask |= 1u << " + index + "u;\n";
        }
    }
    for (usize i = 0; i < c.interpolators.size(); ++i) {
        src += "    lumaInterp" + std::to_string(i) + " = " + c.interpolators[i].vertexCode + ";\n";
    }
    src += "}\n\n#include \"material_template.vert\"\n";
    return src;
}

std::string FragmentSource(const CompiledMaterial& c, const Material::MaterialSettings& s, Pass pass) {
    std::string src = Header(c, s, pass, Stage::Pixel);
    src += "\nvoid LumaMaterialPixel(inout MaterialPixel M) {\n";
    src += c.pixelBody;
    for (const MaterialOutputValue& o : c.outputs) {
        if (o.stage != Stage::Pixel) continue;
        const std::string_view field = FieldOf(o.pin);
        if (!field.empty()) src += "    M." + std::string(field) + " = " + o.code + ";\n";
    }
    src += "}\n\n";
    if (pass != Pass::PostProcess) src += "#include \"material_pixel.glsl\"\n";
    src += std::string("#include \"") + FragmentTemplate(pass) + "\"\n";
    return src;
}

}  // namespace

std::vector<Pass> PassesFor(const Material::MaterialSettings& s) {
    if (s.domain == MaterialDomain::PostProcess) return {Pass::PostProcess};
    if (Translucent(s.blendMode)) return {Pass::Forward, Pass::SelectionMask};
    return {Pass::GBuffer, Pass::DepthOnly, Pass::SelectionMask};
}

void AssemblePasses(CompiledMaterial& c, const Material::MaterialSettings& s) {
    for (Pass pass : PassesFor(s)) {
        PassSource source;
        source.vertex = VertexSource(c, s, pass);
        source.fragment = FragmentSource(c, s, pass);
        c.passes[static_cast<usize>(pass)] = std::move(source);
    }
}

}  // namespace Luma::MaterialCompiler::Detail
