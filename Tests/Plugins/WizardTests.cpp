struct TempDir {
    fs::path root;
    explicit TempDir(const char* name) : root(fs::temp_directory_path() / name) {
        std::error_code ec;
        fs::remove_all(root, ec);
        fs::create_directories(root);
    }
    ~TempDir() {
        std::error_code ec;
        fs::remove_all(root, ec);
    }
};

fs::path Templates() { return fs::path(LUMA_SOURCE_DIR) / "Engine" / "Plugins" / "Templates"; }

PluginWizardRequest MakeRequest(PluginTemplate tmpl, const fs::path& location, std::string name) {
    PluginWizardRequest r;
    r.tmpl = tmpl;
    r.name = std::move(name);
    r.friendlyName = r.name;
    r.author = "Luma";
    r.description = "Generated by tests";
    r.category = "Tests";
    r.location = location;
    r.templateRoot = Templates();
    return r;
}

bool LoadAndStart(DllModuleBackend& backend, const fs::path& searchRoot, const char* pluginName,
                  const char* moduleName, PluginHostServices host, bool editor) {
    backend.SetSearchRoots(std::span<const fs::path>(&searchRoot, 1));
    REQUIRE(backend.IsAvailable(moduleName));
    ModuleManager mgr(backend);
    mgr.SetHostServices(host);
    mgr.SetTarget(editor ? PluginTarget::Editor : PluginTarget::Game);
    std::vector<ManifestError> errors;
    auto desc = ParseDescriptor(
        [](const fs::path& p) {
            std::ifstream in(p, std::ios::binary);
            return std::string((std::istreambuf_iterator<char>(in)), {});
        }(searchRoot / pluginName / (std::string(pluginName) + ".lplugin")),
        searchRoot / pluginName / (std::string(pluginName) + ".lplugin"), errors);
    REQUIRE(desc);
    REQUIRE(errors.empty());
    mgr.SetActivePlugins(std::span<const PluginDescriptor>(&*desc, 1));
    mgr.LoadAllPhases();
    REQUIRE(mgr.IsLoaded(moduleName));
    mgr.ShutdownAll();
    REQUIRE_FALSE(mgr.IsLoaded(moduleName));
    return true;
}

